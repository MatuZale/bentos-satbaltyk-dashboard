const I18nContext = createContext(null);

function interpolate(value, vars) {
  return value.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`);
}

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem("bentos-language") || "pl");

  useEffect(() => {
    localStorage.setItem("bentos-language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    locale: language === "en" ? "en-GB" : "pl-PL",
    t(key, vars = {}) {
      return interpolate(translations[language][key] ?? translations.pl[key] ?? key, vars);
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
